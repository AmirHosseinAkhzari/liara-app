function section(title, body) {
  return `<section class="card"><h2>${esc(title)}</h2>${body}</section>`;
}
function table(headers, rows) {
  if (!rows.length) return '';
  // data-label lets narrow screens show each row as a labeled card (pure CSS, see @media below).
  return `<div class="table"><table><thead><tr>${headers.map((h) => `<th scope="col">${esc(h)}</th>`).join('')}</tr></thead><tbody>${rows.map((r) => `<tr>${r.map((c, i) => `<td data-label="${esc(headers[i])}"${c?.num ? ' class="num"' : ''}>${c?.html ?? esc(c)}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`;
}

// Turn the journal into the report's facts.
export function collectFacts(journal) {
  const entries = journal.filter((e) => e.tool !== 'write_report');
  const actions = entries.filter((e) => !QUIET.has(e.tool) && e.outcome !== 'waiting for confirmation');
  const infra = [];
  const envNames = new Set();
  for (const e of entries) {
    const r = e.result || {};
    // forApp / envVars: which app a service was connected to, and the env var names it got.
    const link = { forApp: r.connectedTo || e.forApp || undefined, envVars: r.envVarNames || undefined };
    if (['done', 'reused'].includes(e.outcome)) {
      if (e.tool === 'create_app' || (e.tool === 'deploy' && e.plan)) infra.push({ kind: 'app', name: r.app || e.target, how: r.created === false || e.outcome === 'reused' ? 'reused' : 'created', plan: e.plan, bundle: e.bundle });
      if (e.tool === 'connect_database') infra.push({ kind: 'database', name: r.database?.hostname || e.target, detail: r.database?.type, how: e.plan ? 'created' : 'configured', plan: e.plan, bundle: e.bundle, ...link });
      if (e.tool === 'connect_storage') infra.push({ kind: 'bucket', name: r.bucket || e.target, how: e.plan ? 'created' : 'configured', plan: e.plan, ...link });
      if (e.tool === 'connect_mail') infra.push({ kind: 'mail', name: e.target, how: e.plan ? 'created' : 'configured', plan: e.plan, ...link });
      if (e.tool === 'connect_dns') infra.push({ kind: 'dns', name: e.target, how: 'configured', forApp: e.forApp || undefined });
      if (e.tool === 'connect_ai') infra.push({ kind: 'ai', name: e.target, how: e.plan ? 'created' : 'configured', plan: e.plan, ...link });
      if (e.tool === 'deploy_service') infra.push({ kind: 'service', name: r.service || e.target, detail: r.image, how: 'created', plan: e.plan, bundle: e.bundle, ...link });
      if (e.tool === 'create_vm') infra.push({ kind: 'vps', name: e.target, how: r.created === false ? 'reused' : 'created', plan: e.plan });
    }
    for (const n of r.envVarNames || []) envNames.add(n);
    for (const n of Array.isArray(r.changed) ? r.changed : []) envNames.add(n);
  }
  const deploys = entries.filter((e) => e.tool === 'deploy' && e.result && e.outcome !== 'declined' && e.outcome !== 'waiting for confirmation');
  const verify = entries.filter((e) => e.tool === 'verify_app' && e.result?.checks).at(-1) || null;
  const diagnoses = entries.filter((e) => e.tool === 'diagnose' && e.result?.category);
  return { entries, actions, infra, envNames: [...envNames].sort(), deploy: deploys.at(-1) || null, verify, diagnoses, accounts: [...new Set(entries.filter((e) => ['change', 'billable', 'destructive'].includes(e.risk) && ['done', 'reused', 'failed'].includes(e.outcome)).map((e) => e.account).filter(Boolean))] };
}

export async function buildReport({ lang = 'en', operation = 'deployment', request, summary, issues = [], remaining = [], docs = [], project = null, api = null, journal = sessionJournal(), now = new Date() }) {
  const f = collectFacts(journal);
  const appName = f.deploy?.result?.app || f.infra.find((i) => i.kind === 'app')?.name || project?.suggestedAppName || '';
  // A deployment gets the Persian page with cards and charts, whatever lang says.
  if (operation === 'deployment') return buildDeployPage({ f, api, now, appName, platform: project?.platform });
  const t = L[lang] || L.en;
  lang = L[lang] ? lang : 'en';
  const title = t.titles[operation] || t.titles.other;
  const parts = [];

  // Summary: a facts line computed from the recorded actions, then Claude's narrative (labeled).
  const failedCount = f.actions.filter((e) => ['failed', 'error'].includes(e.outcome)).length;
  const deployOk = f.deploy?.result?.success === true;
  const healthy = f.verify?.result?.healthy;
  const factsText = lang === 'fa'
    ? `طبق کارهای ثبت‌شده: ${f.deploy ? (deployOk ? 'استقرار موفق بود' : 'استقرار ناموفق بود') : 'استقرار موفقی ثبت نشده است'}${healthy === true ? '، همه‌ی بررسی‌های سلامت موفق بود' : healthy === false ? '، بعضی از بررسی‌های سلامت ناموفق بود' : '، بررسی سلامت انجام نشده است'}${failedCount ? `، ${faDigits(failedCount)} کار با خطا تمام شد` : ''}.`
    : `Recorded facts: ${f.deploy ? (deployOk ? 'the deployment succeeded' : 'the deployment failed') : 'no successful deployment is recorded'}${healthy === true ? ', every health check passed' : healthy === false ? ', some health checks failed' : ', no health check was run'}${failedCount ? `, ${failedCount} action${failedCount === 1 ? '' : 's'} ended with an error` : ''}.`;
  const factsKind = deployOk && healthy === true && !failedCount ? 'ok' : failedCount || f.deploy || healthy === false ? 'fail' : 'muted';
  parts.push(section(t.summary, `<p class="facts facts-${factsKind}">${esc(factsText)}</p>${request ? `<p><strong>${esc(t.request)}:</strong> ${escLong(request)}</p>` : ''}${summary ? `<p class="lead"><strong>${esc(t.done)}:</strong> ${escLong(summary)}</p>` : ''}<p class="note">${esc(t.narrative)}</p>`));

  // Project
  if (project) {
    const kv = [[t.app, appName], [t.framework, project.framework], [t.language, project.language], [t.platform, project.platform],
      [t.port, project.port], [t.runtime, project.runtime ? `${project.runtime.runtime} ${project.runtime.version || '—'} (${project.runtime.status})` : null], [t.account, f.accounts.join(', ')]]
      .filter(([, x]) => x !== null && x !== undefined && x !== '');
    parts.push(section(t.project, `<div class="grid">${kv.map(([k, x]) => `<div class="kv"><span class="k">${esc(k)}</span><span class="v">${v(x)}</span></div>`).join('')}</div>`));
  }

  // Actions
  const names = TOOL_NAMES[lang];
  const actionRows = f.actions.map((e) => [
    { html: v(fmtTime(e.time, lang)), num: true },
    { html: esc(names[e.tool] || e.tool) },
    { html: e.target ? v(e.target) : '—' },
    { html: pill(statusKind(e.outcome), t.status[e.outcome] || e.outcome) + (e.error ? `<br><span class="note"><bdi>${esc(e.error)}</bdi></span>` : '') },
    { html: e.consent ? `<span class="note">${lang === 'fa' ? consentFa(e.consent) : esc(e.consent)}</span>` : '—' },
  ]);
  parts.push(section(t.actions, actionRows.length ? table([t.time, t.action, t.target, t.result, t.approval], actionRows) : `<p class="note">${esc(t.none)}</p>`));

  // Configuration changes
  const d = f.deploy?.result || {};
  const cfg = [];
  if (f.envNames.length) cfg.push(`<p><strong>${esc(t.envVars)}:</strong> ${f.envNames.map((n) => `<bdi class="code">${esc(n)}</bdi>`).join(' ')}</p>`);
  if (d.platform || d.port) cfg.push(`<p><strong>${esc(t.platform)}:</strong> ${v(d.platform || '—')} · <strong>${esc(t.port)}:</strong> ${v(d.port || '—')}</p>`);
  parts.push(section(t.config, cfg.join('') || `<p class="note">${esc(t.none)}</p>`));

  // Infrastructure
  const howLabel = { created: t.created, configured: t.configured, reused: t.reusedRes };
  const kindLabel = (k) => (lang === 'fa' ? esc(KIND_FA[k] || k) : v(k));
  const infraRows = f.infra.map((i) => [{ html: kindLabel(i.kind) }, { html: v(i.name) }, { html: esc(howLabel[i.how] || i.how) }, { html: i.plan ? v(`${i.plan}${i.bundle ? ` + ${i.bundle}` : ''}`) : '—' }]);
  parts.push(section(t.infra, infraRows.length ? table([t.kind, t.name, t.what, t.plan], infraRows) : `<p class="note">${esc(t.none)}</p>`));

  // Deployment result
  if (f.deploy) {
    const url = safeUrl(d.url);
    const ok = d.success === true;
    const kv = [[t.state, `${pill(ok ? 'ok' : 'fail', ok ? t.status.done : t.status.failed)} ${v(d.state || '')}`], [t.app, v(d.app)], [t.url, url ? `<a href="${esc(url)}">${v(url)}</a>` : '—'], [t.release, v(d.releaseID || '—')], [t.time, v(fmtTime(f.deploy.time, lang))], [t.account, v(f.deploy.account || '')]];
    parts.push(section(t.deploy, `<div class="grid">${kv.map(([k, x]) => `<div class="kv"><span class="k">${esc(k)}</span><span class="v">${x}</span></div>`).join('')}</div>`));
  } else parts.push(section(t.deploy, `<p class="note">${esc(t.noDeploy)}</p>`));

  // Health checks
  if (f.verify) {
    const r = f.verify.result;
    const rows = r.checks.map((c) => [{ html: lang === 'fa' ? checkNameFa(c.name) : v(c.name) }, { html: pill(c.ok ? 'ok' : 'fail', c.ok ? t.status.ok : t.status.fail) }, { html: v(c.detail || '') }]);
    for (const n of r.notVerified || []) {
      const fa = lang === 'fa' && NOT_VERIFIED_FA.find(([re]) => re.test(n));
      rows.push([{ html: esc(t.notChecked) }, { html: pill('muted', t.status.skip) }, { html: fa ? esc(fa[1]) : v(n) }]);
    }
    parts.push(section(t.health, `${table([t.check, t.result, t.detail], rows)}<p class="note">${v(fmtTime(f.verify.time, lang))}</p>`));
  } else parts.push(section(t.health, `<p class="note">${esc(t.noHealth)}</p>`));

  // Issues: diagnoses from the journal + what Claude says was done about them
  const issueRows = [
    ...f.diagnoses.map((e) => [{ html: v(e.result.category) }, { html: esc(e.result.explanation || '') }, { html: esc(e.result.suggestedFix || '') }, { html: pill('info', t.status.rec) }]),
    ...issues.map((i) => [{ html: esc(i.problem || '') }, { html: esc(i.cause || '') }, { html: esc(i.fix || '') }, { html: pill(i.resolved ? 'ok' : 'fail', i.resolved ? t.status.fixed : t.status.open) }]),
  ];
  if (issueRows.length) parts.push(section(t.issues, table([t.problem, t.cause, t.fix, t.state], issueRows)));

  // Costs, priced live for the plans actually used
  const billable = f.infra.filter((i) => i.plan && i.how === 'created');
  if (billable.length && api) {
    const rows = []; let total = 0; let fetched = null; let source = null; let complete = true;
    for (const i of billable) {
      const kind = { app: 'app', service: 'app', database: 'database', bucket: 'bucket', mail: 'mail', vps: 'vps' }[i.kind];
      const p = kind ? await priceOf(api, { kind, plan: i.plan, bundle: i.bundle }).catch(() => null) : null;
      if (typeof p?.monthlyToman === 'number') total += p.monthlyToman; else complete = false;
      fetched ||= p?.fetchedAt; source ||= p?.source;
      rows.push([{ html: kindLabel(i.kind) }, { html: v(i.name) }, { html: v(`${i.plan}${i.bundle ? ` + ${i.bundle}` : ''}`) }, { html: esc(toman(p?.monthlyToman, lang)), num: true }]);
    }
    parts.push(section(t.pricing, `${table([t.kind, t.name, t.plan, t.monthly], rows)}<p class="total">${esc(t.total)}: ${esc(toman(total, lang))}${complete ? '' : ' +?'}</p><p class="note">${esc(t.estimateNote)}<br>${esc(t.source)}: ${v(source || '—')} · ${esc(t.fetched)}: ${v(fmtTime(fetched, lang))}</p>`));
  }

  // Remaining tasks
  const auto = [];
  if (f.deploy && f.deploy.result?.success === false) auto.push(lang === 'fa' ? 'استقرار ناموفق بود؛ علت را با diagnose بررسی کنید.' : 'The deployment failed; run diagnose for the cause.');
  if (f.verify && f.verify.result?.healthy === false) auto.push(lang === 'fa' ? 'بعضی از بررسی‌های سلامت ناموفق بودند.' : 'Some health checks failed.');
  const todo = [...remaining, ...auto];
  if (todo.length) parts.push(section(t.remaining, `<ul class="clean">${todo.map((x) => `<li>${escLong(x)}</li>`).join('')}</ul>`));

  // Documentation (https links only)
  const links = docs.map((x) => ({ title: x.title || x.url, url: safeUrl(x.url) })).filter((x) => x.url);
  if (links.length) parts.push(section(t.docs, `<ul class="clean">${links.map((x) => `<li><a href="${esc(x.url)}">${v(x.title)}</a></li>`).join('')}</ul>`));

  const html = `<!DOCTYPE html>
<html lang="${lang}" dir="${t.dir}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="Liara plugin for Claude">
<meta name="description" content="${esc(`${title}${appName ? `: ${appName}` : ''}`)}">
<title>${esc(`${title}${appName ? ` · ${appName}` : ''}`)}</title>
<style>${fontFaces(lang)}${CSS}</style>
</head>
<body>
<header class="top"><div class="wrap">${logoSvg()}<div><h1>${esc(title)}${appName ? ` <bdi>${esc(appName)}</bdi>` : ''}</h1><p class="meta">${esc(t.finished)}: ${v(fmtTime(now.toISOString(), lang))} (${esc(t.tz)})</p></div></div><div class="bar"></div></header>
<main class="wrap">
${parts.join('\n')}
</main>
<footer class="wrap"><p>${esc(t.footer)}</p></footer>
</body>
</html>
`;
  return { html, title, appName, sections: parts.length };
}

// Static checks on the written file before it is handed to the user.
export function checkReport(html) {
  const problems = [];
  if (!html.startsWith('<!DOCTYPE html>')) problems.push('missing doctype');
  // At most one inline script (the deployment page's top-up calculator): no src, no network.
  const scripts = [...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)];
  if (scripts.length !== (html.match(/<script\b/gi) || []).length) problems.push('contains an unclosed script');
  if (scripts.length > 1) problems.push('contains more than one script');
  for (const [, attrs, code] of scripts) {
    if (/\bsrc\s*=/i.test(attrs)) problems.push('loads an external script');
    if (/\b(?:fetch|XMLHttpRequest|WebSocket|EventSource|sendBeacon|importScripts|eval|localStorage|sessionStorage|indexedDB)\b|\bimport\s*\(|\bFunction\s*\(|document\.cookie|\.src\s*=|\bhref\s*=/.test(code)) problems.push('script uses the network or storage');
  }
  const markup = html.replace(/<style>[\s\S]*?<\/style>/, '').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '');
  if (/\bon[a-z]+\s*=\s*["']/i.test(markup)) problems.push('contains an inline event handler');
  if (/javascript:/i.test(html)) problems.push('contains a javascript: URL');
  if (/<(link|img|iframe|object|embed)\b[^>]*(src|href)=["']https?:/i.test(html)) problems.push('loads an external resource');
  if (/@import|url\(["']?https?:/i.test(html)) problems.push('CSS loads an external resource');
  for (const tag of ['html', 'head', 'body', 'main', 'section', 'table', 'header', 'footer']) {
    const open = (html.match(new RegExp(`<${tag}[\\s>]`, 'g')) || []).length;
    const close = (html.match(new RegExp(`</${tag}>`, 'g')) || []).length;
    if (open !== close) problems.push(`<${tag}> opened ${open}, closed ${close}`);
  }
  return { ok: problems.length === 0, problems };
}

export function writeReportFile(root, html, { appName, operation = 'deployment', lang = 'en', now = new Date() }) {
  const dir = path.join(root, 'liara-reports');
  fs.mkdirSync(dir, { recursive: true });
  const stamp = now.toISOString().replace(/[-:]/g, '').slice(0, 15).replace('T', '-');
  const safeApp = String(appName || 'project').toLowerCase().replace(/[^a-z0-9-]+/g, '-').slice(0, 40) || 'project';
  const base = `liara-${operation}-report-${safeApp}-${stamp}-${lang === 'fa' ? 'fa' : 'en'}`;
  // Never overwrite an earlier report.
  let file = path.join(dir, `${base}.html`);
  for (let i = 2; fs.existsSync(file); i++) file = path.join(dir, `${base}-${i}.html`);
  fs.writeFileSync(file, html, { flag: 'wx' });
  return file;
}
