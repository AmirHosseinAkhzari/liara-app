function consentFa(via) {
  if (!via) return '—';
  if (via === 'approved in dialog') return 'تأیید در پنجره‌ی تأیید';
  if (via === 'confirmed in chat') return 'تأیید در گفتگو';
  const m = String(via).match(/^approved plan "(.+)" \(([^)]+)\)$/);
  if (m) return `در برنامه‌ی تأییدشده‌ی «<bdi>${esc(m[1])}</bdi>»`;
  return `<bdi>${esc(via)}</bdi>`;
}

