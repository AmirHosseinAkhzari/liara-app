function checkNameFa(name) {
  const rules = [
    [/^app exists$/, () => 'برنامه در لیارا وجود دارد'],
    [/^app is running$/, () => 'برنامه روشن است'],
    [/^latest release succeeded$/, () => 'آخرین استقرار موفق بود'],
    [/^HTTP (.+)$/, (m) => `درخواست HTTP به <bdi>${esc(m[1])}</bdi>`],
    [/^health (.+)$/, (m) => `مسیر سلامت <bdi>${esc(m[1])}</bdi>`],
    [/^custom domain (.+)$/, (m) => `دامنه‌ی اختصاصی <bdi>${esc(m[1])}</bdi>`],
    [/^no errors in the last (\d+) min of logs$/, (m) => `خطایی در ${faDigits(m[1])} دقیقه‌ی اخیر لاگ‌ها نیست`],
    [/^env vars the code needs are set on Liara$/, () => 'متغیرهای محیطی لازم در لیارا تنظیم شده‌اند'],
  ];
  for (const [re, f] of rules) { const m = String(name).match(re); if (m) return f(m); }
  return `<bdi>${esc(name)}</bdi>`;
}
